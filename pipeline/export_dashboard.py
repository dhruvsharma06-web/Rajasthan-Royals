"""T6: export the dashboard data from the committed pipeline outputs (same files the report reads).

Input : outputs/t3/*, outputs/ratings/*
Output: dashboard/data.js (defines window.RR_DATA; loaded by dashboard/index.html, works from file:// too)
Run from the project root after ratings.py:  python -P pipeline/export_dashboard.py
"""
import json
import math

import polars as pl

T3, RT, OUT = "outputs/t3/", "outputs/ratings/", "dashboard/data.js"

VARIANTS = [  # column in robustness_*.csv -> label shown on the dashboard (order = report order)
    ("threshold_top10pct", "Top 10% threshold"),
    ("threshold_top30pct", "Top 30% threshold"),
    ("pressure_pooled_innings", "Pressure ranked across innings"),
    ("pressure_at_over_start", "Pressure at start of over"),
    ("cautious_10th_pct", "Rank on 10th percentile"),
    ("median_estimate", "Rank on median"),
    ("ipl_only", "IPL only"),
    ("t20i_only", "T20I only"),
    ("recent_2024_2026", "2024-2026 only"),
    ("no_mismatches", "No lopsided matches"),
    ("baseline_by_pace_spin", "Pace/spin baseline"),
    ("no_situation_baseline", "No situation baseline"),
    ("all_balls_no_clutch", "All balls, no clutch"),
    ("pressure_balls_only", "Pressure balls only"),
    ("chase_pressure_only", "Chase pressure only"),
]
COMMON = ["rank", "pid", "name", "rating", "rating_lo", "rating_hi", "p_top10", "pressure_raw", "usual_raw",
          "uplift_raw", "b_hi", "b_or", "hp_inns", "matches", "weight_on_pressure_balls", "share_positive_matches",
          "pressure_matches", "best2_share_of_gains", "share_ipl_balls", "first_year", "last_year"]
ROLE = {
    "batters": ["sr_hp", "avg_hp", "dot_pct_hp", "bnd_pct_hp", "sr_ord", "avg_ord", "dot_pct_ord", "bnd_pct_ord"],
    "bowlers": ["econ_hp", "balls_per_wkt_hp", "dot_pct_hp", "bnd_pct_hp", "econ_ord", "balls_per_wkt_ord",
                "dot_pct_ord", "bnd_pct_ord"],
}


def clean(v):
    if isinstance(v, float):
        return None if math.isnan(v) or math.isinf(v) else round(v, 5)
    return v


def rows(df):
    return [{k: clean(v) for k, v in r.items()} for r in df.iter_rows(named=True)]


summ = json.load(open(T3 + "summary.json"))
rel = json.load(open(RT + "reliability.json"))
val = pl.read_csv(T3 + "pressure_vs_ordinary.csv")
dec = pl.read_csv(T3 + "decided_share.csv").row(0, named=True)
mv = val.with_columns((pl.col("balls") * pl.col("mean_abs_wp_swing")).alias("move"))

data = {
    "meta": {
        "matches": summ["scope_matches"], "balls": summ["scope_balls"], "years": summ["years"],
        "threshold": "top 20% of stakes within format and innings",
        "eligibility": rel["settings"]["eligibility"], "bootstrap": rel["settings"]["bootstrap_main"],
        "rank_quantile": rel["settings"]["rank_quantile"],
        "hp_move_share": clean(mv.filter(pl.col("high_pressure"))["move"].sum() / mv["move"].sum()),
        "hp_ball_share": clean(mv.filter(pl.col("high_pressure"))["balls"].sum() / mv["balls"].sum()),
        "decided": {k: clean(v) for k, v in dec.items()},
        "ece": {k: clean(v) for k, v in summ["ece"].items()},
        "heldout": [{k: clean(v) for k, v in m.items()} for m in summ["heldout"]],
        "repo": "https://github.com/dhruvsharma06-web/Rajasthan-Royals",
    },
    "variants": [{"key": k, "label": l} for k, l in VARIANTS],
    "validation": rows(val),
    "calibration": rows(pl.read_csv(T3 + "calibration.csv")),
    "grid": rows(pl.read_csv(T3 + "pressure_grid.csv")),
}
for role in ("batters", "bowlers"):
    res = pl.read_csv(RT + f"{role}.csv").select(COMMON + ROLE[role])
    rob = pl.read_csv(RT + f"robustness_{role}.csv")
    assert rob.columns[3:-3] == [k for k, _ in VARIANTS], rob.columns
    assert (rob.join(res.select("pid", "rank"), on="pid")["main"] == rob.join(res.select("pid", "rank"), on="pid")["rank"]).all()
    out = res.join(rob.drop("name", "main"), on="pid", how="left").sort("rank")
    assert out.height == res.height and out["rank"].to_list() == list(range(1, res.height + 1))
    top = pl.read_csv(RT + f"top10_{role}.csv").sort("rank")
    assert out.head(10)["pid"].to_list() == top["pid"].to_list()
    data[role] = rows(out)
    sh = rel[role]["split_half"]
    data.setdefault("reliability", {})[role] = {
        "eligible": rel[role]["main"]["eligible"],
        "weight_on_pressure_balls": clean(rel[role]["main"]["mean_weight_on_pressure_balls"]),
        "split_half": {k: sh[k]["r_half"] for k in ("pressure_raw", "all_raw", "usual_raw", "uplift_raw")},
        "split_half_players": sh["uplift_raw"]["players"],
        "clutch_bound": clean(rel[role]["clutch_power"]["tau_u2_upper90"]),
        "clutch_noise": clean(rel[role]["clutch_power"]["half_sample_noise_var"]),
    }

with open(OUT, "w") as f:
    f.write("// Generated by pipeline/export_dashboard.py from outputs/. Do not edit by hand.\n")
    f.write("window.RR_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("wrote", OUT, f"({len(data['batters'])} batters, {len(data['bowlers'])} bowlers)")
print("OK")
